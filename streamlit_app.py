import streamlit as st
import datetime
from dotenv import load_dotenv
from agent.agentic_workflow import GraphBuilder

load_dotenv()

st.set_page_config(
    page_title="Travel Planner Agentic Application",
    page_icon="🌍",
    layout="centered",
    initial_sidebar_state="expanded",
)

st.sidebar.title("About this app")
st.sidebar.markdown(
    """
    **AI Travel Planner Flow**

    1. User submits a trip request (destination, duration, budget, preferences).
    2. The app builds an agentic workflow to analyze the request.
    3. Agents collaborate to gather and organize travel details.

    **Agents involved**

    - **Price Conversion Agent**: Converts currencies and estimates costs.
    - **Place Search Agent**: Finds destinations, attractions, and local points of interest.
    - **Hotel Search Agent**: Recommends hotels and stays based on user needs.
    - **Weather Info Agent**: Provides local weather guidance for the trip.
    - **Expense Calculator Agent**: Estimates daily and overall travel expenses.
    - **Fallback Agent**: Handles unknown questions and ensures smooth responses.

    **Note**: This content is static and for reference only. Always verify final details before booking.
    """
)

st.title("🌍 Travel Planner Agentic Application")

# Initialize chat history
if "messages" not in st.session_state:
    st.session_state.messages = []

# Display chat history
st.header("How can I help you in planning a trip? Let me know where do you want to visit.")

# Chat input box at bottom
with st.form(key="query_form", clear_on_submit=True):
    user_input = st.text_input("User Input", placeholder="e.g. Plan a trip to Goa for 5 days")
    submit_button = st.form_submit_button("Send")

if submit_button and user_input.strip():
    try:
        with st.spinner("Bot is thinking..."):
            graph = GraphBuilder(model_provider="groq")
            react_app = graph()

            # try to save a mermaid PNG if available (non-fatal)
            try:
                png_graph = react_app.get_graph().draw_mermaid_png()
                with open("my_graph.png", "wb") as f:
                    f.write(png_graph)
            except Exception:
                pass

            messages = {"messages": [user_input]}
            output = react_app.invoke(messages)

        if isinstance(output, dict) and "messages" in output:
            answer = output["messages"][-1].content
        else:
            answer = str(output)

        markdown_content = f"""# 🌍 AI Travel Plan

# **Generated:** {datetime.datetime.now().strftime('%Y-%m-%d at %H:%M')}  

---

{answer}

---

*This travel plan was generated by AI. Please verify all information, especially prices, operating hours, and travel requirements before your trip.*
"""
        st.markdown(markdown_content)

    except Exception as e:
        st.error(f"The response failed due to: {e}")